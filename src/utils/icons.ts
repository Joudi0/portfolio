/**
 * Replaces every `<i data-lucide="name">` placeholder with its inline SVG.
 * Call again after injecting markup (e.g. modal content).
 */
export function renderIcons(root: Element | Document = document): void {
  createIcons({
    icons: ICONS,
    attrs: { 'aria-hidden': 'true', 'stroke-width': '1.75' },
    root
  });
}
